#!/usr/bin/env node
// Generates every room-dependent file from rooms.json:
//   firmware/rooms/<host>-occ.yaml, firmware/rooms/<host>-ac.yaml
//   ha/packages/cc_house.yaml, ha/packages/cc_room_<slug>.yaml
// Run:  npm run generate
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(readFileSync(join(root, "rooms.json"), "utf8"));
const rooms = cfg.rooms;
// The Kelvin printed on the LED strip: its warm-only and cool-only ends.
const [stripWarm, stripCool] = cfg.strip_kelvin ?? [2700, 6500];
// Which radar the presence nodes carry: "ld2410" (HLK-LD2410C) or "ld2412" (HLK-LD2412).
const radar = cfg.radar ?? "ld2410";
if (!["ld2410", "ld2412"].includes(radar)) {
  throw new Error(`rooms.json: "radar" must be "ld2410" or "ld2412", got "${radar}"`);
}
// The optional second radar on a presence node. It tracks where people are, for the room map:
// "ld2450" (HLK-LD2450) or "none". Set it for the house, or per room to override.
const trackerOf = (r) => {
  const tracker = r.tracker ?? cfg.tracker ?? "none";
  if (!["ld2450", "none"].includes(tracker)) {
    throw new Error(`rooms.json: "tracker" must be "ld2450" or "none", got "${tracker}" (${r.slug})`);
  }
  return tracker;
};
const banner = "# Generated by tools/generate.mjs from rooms.json. Edit the generator, not this file.\n";

function write(rel, text) {
  const path = join(root, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
  console.log("wrote", rel);
}

function clean(dir, test) {
  const abs = join(root, dir);
  mkdirSync(abs, { recursive: true });
  for (const f of readdirSync(abs)) if (test(f)) rmSync(join(abs, f));
}

// ---------------------------------------------------------------- firmware
clean("firmware/rooms", (f) => f.endsWith("-occ.yaml") || f.endsWith("-ac.yaml"));
for (const r of rooms) {
  write(
    `firmware/rooms/${r.host}-occ.yaml`,
    `${banner}substitutions:
  host: occ-${r.host}
  room_name: ${r.name}
  role: Presence node

packages:
  base: !include ../packages/base.yaml
  device: !include ../packages/presence-${radar}.yaml
${trackerOf(r) === "none" ? "" : `  tracker: !include ../packages/tracker-${trackerOf(r)}.yaml\n`}`,
  );
  write(
    `firmware/rooms/${r.host}-ac.yaml`,
    `${banner}substitutions:
  host: ac-${r.host}
  room_name: ${r.name}
  role: AC bridge

packages:
  base: !include ../packages/base.yaml
  device: !include ../packages/minisplit-${cfg.minisplit}.yaml
`,
  );
}

